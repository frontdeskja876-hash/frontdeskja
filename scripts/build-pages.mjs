// Generates the document pages that share the site chrome:
//   - the Ask FrontDesk hub (ask-frontdesk.html) and one page per article
//     (ask/<slug>.html) from content/articles.json — the same file the Ask FrontDesk
//     Assistant reads, so the site and the chat never disagree
//   - the About page (about.html), final copy from spec §13
//
//   npm run build:pages
import { readFileSync, writeFileSync, mkdirSync, readdirSync, unlinkSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const { pillars, articles } = JSON.parse(readFileSync(join(root, 'content/articles.json'), 'utf8'));

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const minutes = (a) => Math.max(1, Math.ceil(a.paragraphs.join(" ").split(/\s+/).length / 220));
const pillarOf = (id) => pillars.find((p) => p.id === id) || pillars[pillars.length - 1];

const symbols = `<svg width="0" height="0" style="position:absolute" aria-hidden="true" focusable="false">
    <symbol id="fd-mark" viewBox="0 0 61 43">
      <path fill="currentColor" d="M1 2h42a16.5 19.25 0 0 1 0 38.5H22v-8h21a8 11.25 0 0 0 0-22.5H1z"/>
      <path fill="currentColor" d="M1 17.5h33v8H9.5v15H1z"/>
    </symbol>
    <symbol id="i-arrow" viewBox="0 0 24 24">
      <path fill="none" stroke="currentColor" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round" d="M4 12h15m-6-6 6 6-6 6"/>
    </symbol>
  </svg>`;

