function card(a, base) {
  const p = pillarOf(a.pillar);
  return `        <li>
          <a class="article-card lift" href="${base}ask/${a.slug}.html" data-pillar="${p.id}">
            <span class="article-card__meta"><i class="dot"></i>${esc(a.category)} · ${minutes(a)} min read</span>
            <span class="article-card__title">${esc(a.title)}</span>
            <span class="article-card__summary">${esc(a.summary)}</span>
            <span class="article-card__go">Read <svg aria-hidden="true"><use href="#i-arrow"/></svg></span>
          </a>
        </li>`;
}

/* ---------- hub ---------- */
const sections = pillars
  .map((p) => ({ p, list: articles.filter((a) => a.pillar === p.id) }))
  .filter((s) => s.list.length)
  .map(({ p, list }) => `    <section class="hub__group" data-pillar="${p.id}" aria-labelledby="g-${p.id}">
      <header class="hub__group-head">
        <p class="eyebrow">${esc(p.name)} — ${esc(p.tagline)}</p>
        <p class="hub__group-intro" id="g-${p.id}">${esc(p.intro)}</p>
      </header>
      <ul class="hub__list">
${list.map((a) => card(a, '')).join('\n')}
      </ul>
    </section>`).join('\n\n');

const hub = page({
  base: '',
  title: 'Ask FrontDesk — FrontDesk JA',
  description: 'Clear answers about AI and running a business: AEO and AI search, digital front desks, missed calls and AI receptionists.',
  current: 'hub',
  body: `  <main id="main" class="hub">
    <section class="hub__intro is-in" data-page aria-labelledby="h-hub">
      <p class="eyebrow r">Ask FrontDesk</p>
      <h1 class="headline headline--wide" id="h-hub">
        <span class="ln"><span>Ask FrontDesk.</span></span>
        <span class="ln ln--light"><span>Answers about AI and business.</span></span>
      </h1>
      <p class="body r">Real questions business owners ask about AI search, digital front desks and missed calls, answered in plain language and organized by topic.</p>
      <p class="r"><button class="btn btn--ghost" type="button" data-ask>Ask your own question <svg aria-hidden="true"><use href="#i-arrow"/></svg></button></p>
    </section>

${sections}
  </main>`
});
writeFileSync(join(root, 'ask-frontdesk.html'), hub);

/* ---------- articles ---------- */
mkdirSync(join(root, 'ask'), { recursive: true });
for (const f of readdirSync(join(root, 'ask'))) if (f.endsWith('.html')) unlinkSync(join(root, 'ask', f));

for (const a of articles) {
  const p = pillarOf(a.pillar);
  const related = articles.filter((x) => x.slug !== a.slug)
    .sort((x, y) => (y.pillar === a.pillar) - (x.pillar === a.pillar)).slice(0, 2);
  const html = page({
    base: '../',
    title: `${a.title} — Ask FrontDesk`,
    description: a.summary,
    current: 'article',
    body: `  <main id="main" class="article" data-pillar="${p.id}">
    <article>
      <header class="article__head">
        <nav class="article__crumbs" aria-label="Breadcrumb"><a href="../ask-frontdesk.html">Ask FrontDesk</a><span aria-hidden="true">/</span><span>${esc(p.name)}</span></nav>
        <h1 class="article__title">${esc(a.title)}</h1>
        <p class="article__meta"><i class="dot"></i>${esc(a.category)} · ${minutes(a)} min read</p>
      </header>
      <div class="article__body">
${a.paragraphs.map((t) => `        <p>${esc(t)}</p>`).join('\n')}
      </div>
    </article>

    <aside class="article__ask" aria-label="Ask about this">
      <p class="article__ask-title">Have a question about your business?</p>
      <p>Ask FrontDesk’s own Assistant. It answers from articles like this one and from what FrontDesk offers.</p>
      <button class="btn" type="button" data-ask data-ask-question="${esc(`I just read “${a.title}”. How does this apply to my business?`)}">Ask about this <svg aria-hidden="true"><use href="#i-arrow"/></svg></button>
    </aside>

    <section class="article__related" aria-labelledby="related">
      <p class="eyebrow" id="related">Keep reading</p>
      <ul class="hub__list">
${related.map((r) => card(r, '../')).join('\n')}
      </ul>
    </section>
  </main>`
  });
  writeFileSync(join(root, 'ask', `${a.slug}.html`), html);
}

